function buildProjects(items) {
  const projectMap = new Map();
  const projects = [];

  items.forEach((item) => {
    const custom = customProjectFor(item);
    const relativePath = item.src.replace('./assets/gallery/', '').split('/');
    const nestedFolder = relativePath.length > 3 ? relativePath[2] : null;
    const key = custom?.key || (nestedFolder
      ? item.category + '::' + nestedFolder
      : item.category + '::' + item.src);

    if (!projectMap.has(key)) {
      const project = {
        key,
        category: custom?.category || item.category,
        title: custom?.title || nestedFolder || item.title,
        coverSrc: custom?.coverSrc || null,
        coverPosition: custom?.coverPosition || null,
        description: custom?.description || "",
        isGroup: Boolean(custom || nestedFolder),
        items: []
      };
      projectMap.set(key, project);
      projects.push(project);
    }

    projectMap.get(key).items.push(item);
  });

  return projects;
}

