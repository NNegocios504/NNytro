function buildProjects(items) {
  const projectMap = new Map();
  const projects = [];

  items.forEach((item) => {
    const seeded = customProjectFor(item);
    const custom = item.adminEntryId ? null : seeded;
    const relativePath = item.src.startsWith('./assets/gallery/') ? item.src.replace('./assets/gallery/', '').split('/') : [];
    const nestedFolder = relativePath.length > 3 ? relativePath[2] : null;
    const key = item.adminEntryId ? `admin:${item.adminEntryId}` : custom?.key || (nestedFolder
      ? item.category + '::' + nestedFolder
      : item.category + '::' + item.src);

    if (!projectMap.has(key)) {
      const project = {
        key,
        sourceKey: item.sourceKey || '',
        category: custom?.category || item.category,
        title: custom?.title || nestedFolder || item.title,
        coverSrc: custom?.coverSrc || null,
        coverPosition: custom?.coverPosition || null,
        description: custom?.description || item.description || "",
        sketchfabModels: item.sketchfabConfigured
          ? (item.sketchfabModels || [])
          : (item.sketchfabModels?.length ? item.sketchfabModels : seeded?.sketchfabModels || (seeded?.sketchfabId ? [{ id: seeded.sketchfabId, url: seeded.sketchfabUrl || '', title: seeded.title || custom?.title || item.title }] : [])),
        organization: item.organization || null,
        isGroup: Boolean(custom || nestedFolder),
        items: []
      };
      projectMap.set(key, project);
      projects.push(project);
    }

    projectMap.get(key).items.push(item);
  });

  return projects.map(project => {
    if (project.items.some(item => item.adminEntryId) && project.items.length > 1) project.isGroup = true;
    return project;
  });
}

